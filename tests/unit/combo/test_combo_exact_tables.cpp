// Every counting sequence in ms::combo, checked over its whole documented range
// against values computed in arbitrary-precision arithmetic outside this program.
//
// The module's contract is a table of caps -- factorial past 20, Catalan past 36,
// Bell past 25, and so on -- each said to be "the largest argument whose exact value
// still fits in uint64_t", with UINT64_MAX returned beyond it. That contract has two
// halves, and only the second was ever tested. Nothing checked that the values below
// the cap were right.
//
// One was not. catalan_num computed C(2n,n)/(n+1), which is the definition rather
// than a way to evaluate it: the central binomial overflows three steps before the
// Catalan number does, so catalan_num(34), (35) and (36) were wrong while sitting
// inside the range the cap declares safe. C(36) is 11959798385860453492 and fits
// comfortably; the function returned 527049830677415760 for C(34) and similar
// nonsense for the other two.
//
// So: the whole range, every argument, against an independent computation. The tables
// below were generated with Python's arbitrary-precision integers -- factorial and
// math.comb for the closed forms, the standard recurrences carried in exact integers
// for the rest -- and every entry was checked to fit in uint64_t before being written
// out. A cap is confirmed from both sides: the last argument produces its exact value,
// and the next one declines.

