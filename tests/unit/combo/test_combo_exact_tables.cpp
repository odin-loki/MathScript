template <std::size_t N>
void check_sequence(const char* name, const uint64_t (&expected)[N], uint64_t (*fn)(uint32_t)) {
    for (uint32_t n = 0; n < N; ++n) {
        ASSERT_EQ(fn(n), expected[n]) << name << "(" << n << ")";
    }
    // One past the cap has no representable answer.
    EXPECT_EQ(fn(static_cast<uint32_t>(N)), kOverflow) << name << " should decline " << N;
}

template <std::size_t N>
void check_triangle(const char* name, const uint64_t (&flat)[N], uint32_t cap,
                    uint64_t (*fn)(uint32_t, uint32_t)) {
    std::size_t at = 0;
    for (uint32_t n = 0; n <= cap; ++n) {
        for (uint32_t k = 0; k <= n; ++k) {
            ASSERT_LT(at, N) << name << " table is short at n=" << n << " k=" << k;
            ASSERT_EQ(fn(n, k), flat[at]) << name << "(" << n << ", " << k << ")";
            ++at;
        }
    }
    EXPECT_EQ(at, N) << name << " table has unused entries";
    EXPECT_EQ(fn(cap + 1, 1), kOverflow) << name << " should decline n=" << (cap + 1);
}

TEST(ComboExactTables, Factorial) {
    check_sequence("factorial", kFactorial, &factorial);
}

